#!/usr/bin/env bash
# DSQL scenario: functions and procedures under --manage-routine. SQL and
# PL/pgSQL routines are created, changed, used from a column default and a
# view, and dropped, and dump plans clean.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "$SCRIPT_DIR/helper.sh"

export PISTA_MANAGE_ROUTINE=1

cat > "$WORK/v1.sql" <<'EOS'
CREATE TABLE accounts (
    id      bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1),
    balance numeric(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT accounts_pkey PRIMARY KEY (id)
);

CREATE FUNCTION add(a integer, b integer) RETURNS integer
    LANGUAGE sql IMMUTABLE
    AS $$ SELECT a + b $$;

COMMENT ON FUNCTION add(integer, integer) IS 'adds two integers';

CREATE FUNCTION balance_of(p_id bigint) RETURNS numeric
    LANGUAGE plpgsql
    AS $$
BEGIN
  RETURN coalesce((SELECT balance FROM public.accounts WHERE id = p_id), 0);
END;
$$;

CREATE PROCEDURE deposit(p_id bigint, p_amount numeric)
    LANGUAGE plpgsql
    AS $$
BEGIN
  UPDATE public.accounts SET balance = balance + p_amount WHERE id = p_id;
END;
$$;
EOS

reset_db

# --- Step 0: build the routines ---
run_step "00 build routines" "$(cat <<'EOS'
CREATE TABLE public.accounts (
CREATE OR REPLACE FUNCTION public.add(a integer, b integer)
COMMENT ON FUNCTION public.add(integer, integer) IS 'adds two integers';
CREATE OR REPLACE FUNCTION public.balance_of(p_id bigint)
CREATE OR REPLACE PROCEDURE public.deposit(p_id bigint, p_amount numeric)
EOS
)" "$WORK/v1.sql" || true

# --- Step 1: dump plans clean ---
step "01 dump plans clean"
if ! out=$("$PISTA" dump > "$WORK/dump.sql" 2>&1); then
  fail "dump failed: $out"
elif ! out=$(pista_plan "$WORK/dump.sql") || ! printf '%s\n' "$out" | grep -qF -e '-- No changes'; then
  fail "expected no changes when the dump is fed back: $out"
else
  pass
fi

# --- Step 2: change bodies and attributes, and replace a procedure ---
derive "$WORK/v2.sql" "$WORK/v1.sql" '
  s/SELECT a \+ b /SELECT a + b + 0 /;
  s/adds two integers/adds two integers, v2/;
  s/(RETURNS numeric\n    LANGUAGE plpgsql)/$1 STABLE/;
  s/PROCEDURE deposit/PROCEDURE withdraw/;
  s/balance \+ p_amount/balance - p_amount/;
'
run_step "02 change routines" "$(cat <<'EOS'
    AS $$ SELECT a + b + 0 $$;
COMMENT ON FUNCTION public.add(integer, integer) IS 'adds two integers, v2';
    STABLE
CREATE OR REPLACE PROCEDURE public.withdraw(p_id bigint, p_amount numeric)
DROP PROCEDURE public.deposit(bigint, numeric);
EOS
)" "$WORK/v2.sql" || true

# --- Step 3: change a return type, and use routines from a default and a
#     view ---
derive "$WORK/v3.sql" "$WORK/v2.sql" '
  s/RETURNS integer/RETURNS bigint/;
  s/SELECT a \+ b \+ 0 /SELECT (a + b)::bigint /;
  s/DEFAULT 0/DEFAULT public.add(0, 0)/;
'
cat >> "$WORK/v3.sql" <<'EOS'

CREATE VIEW account_balances AS
    SELECT id, public.balance_of(id) AS balance FROM public.accounts;
EOS
run_step "03 change a return type and depend on routines" "$(cat <<'EOS'
DROP FUNCTION public.add(integer, integer);
    RETURNS bigint
ALTER TABLE public.accounts ALTER COLUMN balance SET DEFAULT public.add(0, 0);
CREATE OR REPLACE VIEW public.account_balances AS
EOS
)" "$WORK/v3.sql" || true

# --- Step 4: drop everything ---
run_step "04 drop everything" "$(cat <<'EOS'
DROP VIEW public.account_balances;
DROP TABLE public.accounts;
DROP FUNCTION public.add(integer, integer);
DROP FUNCTION public.balance_of(bigint);
DROP PROCEDURE public.withdraw(bigint, numeric);
EOS
)" "$WORK/empty.sql" || true

summary
