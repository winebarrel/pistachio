// TestConformance runs each case against the proxy, or against the cluster
// TEST_PISTA_DSQL_CONN_STR names, and reports every case that answers
// differently. scripts/record-dsql.sh runs it against the cluster.
func TestConformance(t *testing.T) {
	ctx := context.Background()
	var conn *pgx.Conn
	if connString := os.Getenv("TEST_PISTA_DSQL_CONN_STR"); connString != "" {
		var err error
		conn, err = pgx.Connect(ctx, connString)
		require.NoError(t, err)
		t.Cleanup(func() { conn.Close(ctx) }) //nolint:errcheck
	} else {
		conn = connect(t)
	}

	teardown := func() {
		for _, sql := range conformanceTeardown {
			conn.PgConn().Exec(ctx, sql).ReadAll() //nolint:errcheck
		}
	}
	teardown()
	t.Cleanup(teardown)
	for _, sql := range conformanceSetup {
		require.NoError(t, run(ctx, conn, sql), sql)
	}

	for _, tc := range conformanceCases {
		t.Run(tc.sql, func(t *testing.T) {
			err := run(ctx, conn, tc.sql)
			if err == nil && tc.undo != "" {
				require.NoError(t, run(ctx, conn, tc.undo), tc.undo)
			}
			if tc.code == "" {
				assert.NoError(t, err)
				return
			}
			var pgErr *pgconn.PgError
			if assert.ErrorAs(t, err, &pgErr) {
				assert.Equal(t, tc.code, pgErr.Code)
				assert.Equal(t, tc.msg, pgErr.Message)
			}
		})
	}
}

// run sends sql with the simple protocol and waits for the job a statement
// with ASYNC starts.
func run(ctx context.Context, conn *pgx.Conn, sql string) error {
	results, err := conn.PgConn().Exec(ctx, sql).ReadAll()
	if err != nil {
		return err
	}
	for _, r := range results {
		if len(r.FieldDescriptions) != 1 || r.FieldDescriptions[0].Name != "job_id" || len(r.Rows) != 1 {
			continue
		}
		var succeeded bool
		if err := conn.QueryRow(ctx, "CALL sys.wait_for_job($1)", string(r.Rows[0][0])).Scan(&succeeded); err != nil {
			return err
		}
		if !succeeded {
			return errors.New("job " + string(r.Rows[0][0]) + " failed")
		}
	}
	return nil
}
