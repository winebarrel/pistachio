// conformanceCase is one statement and what DSQL answers it with, as DSQL.md
// records it.
type conformanceCase struct {
	sql  string // run alone, in autocommit
	code string // "" when the statement succeeds, else its SQLSTATE
	msg  string // the refusal message, matched exactly
	undo string // run when the statement succeeds, to put things back
}

const refused = "0A000"

